def files():
    """Enumerate only authored files, excluding all private/runtime/dependency trees."""
    paths = []
    for directory, subdirectories, names in os.walk(ROOT):
        subdirectories[:] = [name for name in subdirectories if name not in EXCLUDED]
        for name in names:
            path = Path(directory) / name
            if not name.startswith(".coverage") and path.is_file():
                paths.append(path)
    return sorted(
        paths,
        key=lambda path: path.relative_to(ROOT).as_posix(),
    )


def render():
    """Map Python declarations/parameters/assigned variables to exact physical lines without executing source."""
    catalog = [
        "# File catalog",
        "",
        "By Jason Stys. Generated by `python tools/docs_index.py`.",
        "",
        "| File | Responsibility |",
        "| --- | --- |",
    ]
    source_map = [
        "# Source declaration map",
        "",
        "By Jason Stys. Each source header links here to avoid stale hand-maintained line numbers.",
        "Parameters are listed on their function's declaration line; assigned names are indexed separately.",
        "Descriptions are in file/function/class headers. TS uses TypeScript AST; CSS/HTML have file responsibilities, not executable functions.",
        "",
        "| File | Line | Declaration / variable |",
        "| --- | ---: | --- |",
    ]
    for path in files():
        relative = path.relative_to(ROOT).as_posix()
        text = path.read_text(encoding="utf-8")
        description = FILE_DESCRIPTIONS.get(relative) or next(
            (line.strip(' #/*!-"<>') for line in text.splitlines() if "Jason Stys:" in line),
            None,
        )
        if description is None:
            raise ValueError(f"Add a meaningful file responsibility for {relative}")
        catalog.append(f"| `{relative}` | {description.replace('|', '/')} |")
        if path.suffix == ".py":
            tree = ast.parse(text)
            records = []
            for node in ast.walk(tree):
                if isinstance(node, (ast.ClassDef, ast.FunctionDef, ast.AsyncFunctionDef)):
                    params = (
                        ", ".join(arg.arg for arg in node.args.args)
                        if not isinstance(node, ast.ClassDef)
                        else "class"
                    )
                    records.append((node.lineno, f"{node.name}({params})"))
                elif isinstance(node, ast.Name) and isinstance(node.ctx, ast.Store):
                    records.append((node.lineno, node.id))
            for line, name in sorted(set(records)):
                source_map.append(f"| `{relative}` | {line} | `{name}` |")
    node_binary = shutil.which("node")
    if node_binary is None:
        raise RuntimeError("Node.js is required for the TypeScript source map")
    node = subprocess.check_output(
        [node_binary, "tools/source_index.mjs"], cwd=ROOT, text=True, timeout=30
    )
    source_map.extend(node.strip().splitlines())
    return {
        "docs/FILE_CATALOG.md": "\n".join(catalog) + "\n",
        "docs/SOURCE_MAP.md": "\n".join(source_map) + "\n",
    }


def main():
    """Generate the two fixed docs or fail if checked-in navigation is stale."""
    outputs = render()
    for name, content in outputs.items():
        path = ROOT / name
        if "--check" in sys.argv:
            if not path.exists() or path.read_text(encoding="utf-8") != content:
                raise SystemExit(f"Stale {name}; run python tools/docs_index.py")
        else:
            path.parent.mkdir(exist_ok=True)
            path.write_text(content, encoding="utf-8")
    print(f"Source/file indexes verified for {len(files())} files")


if __name__ == "__main__":
    main()
